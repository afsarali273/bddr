/**
 * The phase 0 experiment: does healing fix cosmetic changes, and does a real bug ever end green?
 *   npx tsx experiment/run-experiment.ts      -> prints a summary and writes experiment/RESULTS.md
 */
import { cpSync, existsSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BUGS, COSMETIC, ENVIRONMENT, createApp } from '../app/shop.js';
import { LocatorHealer } from '../src/agents.js';
