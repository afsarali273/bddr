import { loadApprovals, scan } from '../src/project.js';
import { runAll } from '../src/runner.js';
import { runWithRetry } from '../src/runtime.js';
import { ADVERSARIES } from './adversaries.js';

const root = join(import.meta.dirname, '..');
const work = join(import.meta.dirname, '.work');
const tmpDir = join(root, '.tmp');
const out: string[] = [];
const say = (s = '') => {
  out.push(s);
  console.log(s);
};
const fresh = (name: string) => {
  const d = join(work, name);
  rmSync(d, { recursive: true, force: true });
  cpSync(join(root, 'tests'), d, { recursive: true });
  return d;
};
const app = (m: string[]) => (attempt: number) => createApp(m, { attempt });

const t0 = performance.now();
say('# Prompt-test POC: experiment results');
say();
say(`Generated by \`npx tsx experiment/run-experiment.ts\`. Agent for healing: the deterministic locator healer (no model).`);

// ---------------------------------------------------------------- 1. baseline
const baseDir = fresh('baseline');
const tb = performance.now();
const base = await runAll({ dir: baseDir, tmpDir, fixtures: app([]), heal: 'write', agent: new LocatorHealer() });
const baseMs = Math.round(performance.now() - tb);
